import assert from 'node:assert/strict';
import {ReaderData} from '../web/data.js';
import {configureFileLinks,fileLink,route} from '../web/ui/elements.js';
import {ReaderTheme} from '../web/theme.js';

let input='';
for await(const chunk of process.stdin)input+=chunk;
const data=new ReaderData(JSON.parse(input));
assert.equal(data.catalog().counts.files,3);
assert.equal(data.layout().widgets[0].type,'header');
assert.equal(data.document('docs/guide.md').id,'docs/guide.md');
assert.throws(()=>data.document('__proto__'),/Document not found/);
assert.throws(()=>data.document('absent.md'),/Document not found/);
assert.equal(data.search('rectangular envelope','documents','product').length,1);
assert.equal(data.search('docs/guide.md','documents','product').length,1);
assert.equal(data.search('absent phrase','documents','product').length,0);
assert.equal(data.search('picture','images','product').length,1);
assert.throws(()=>data.search('','invalid',''),/Unknown search kind/);
configureFileLinks(data.files());
const imageLink=fileLink('docs/expected/a picture.png');
assert.doesNotMatch(imageLink,/^(?:[a-z][a-z\d+.-]*:|\/)/i);
assert.ok(imageLink.includes('a%20picture.png'));
assert.equal(new URL(imageLink,'file:///checkout/docs/viewer/index.html').href,'file:///checkout/docs/expected/a%20picture.png');
assert.equal(fileLink('absent'),route({missing:'absent'}));
const preferences=new Map();
const storage={getItem:key=>preferences.get(key),setItem:(key,value)=>preferences.set(key,value)};
const theme=new ReaderTheme(storage);
assert.equal(theme.value,'dark');
theme.toggle();
const restored=new ReaderTheme(storage),root={dataset:{}};
restored.apply(root);
assert.equal(root.dataset.theme,'light');
const unavailable=new ReaderTheme({getItem(){throw Error('unavailable');},setItem(){throw Error('unavailable');}});
assert.equal(unavailable.toggle(),'light');
console.log('Embedded navigation, search and links pass.');
